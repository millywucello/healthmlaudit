test_that("report writes aggregate output, intervals, and a calibration PNG", {
  a <- audit_binary(demo_predictions,"outcome","predicted_risk")
  g <- audit_subgroups(a,"age_group")
  ci <- bootstrap_ci(a,times=20)
  path <- tempfile(fileext=".md")
  out <- generate_report(a,g,ci,file=path)
  on.exit(unlink(unlist(out)))
  expect_true(all(file.exists(unlist(out))))
  text <- paste(readLines(out$report),collapse="\n")
  expect_match(text,"Bootstrap intervals")
  expect_match(text,"400 of 400")
  expect_match(text,"independent observations")
  expect_false(grepl("S001",text,fixed=TRUE))
  expect_gt(file.info(out$figure)$size,1000)
  expect_error(generate_report(a,file=path),"already exists")
  expect_silent(generate_report(a,file=path,overwrite=TRUE))
})

test_that("report rejects incompatible results and bad destinations", {
  a <- audit_binary(demo_predictions,"outcome","predicted_risk")
  b <- audit_binary(demo_predictions,"outcome","predicted_risk",threshold=.6)
  g <- audit_subgroups(b,"age_group")
  expect_error(generate_report(a,g,file=tempfile(fileext=".md")),"same audit")
  expect_error(generate_report(a,ci_result=data.frame(),file=tempfile(fileext=".md")),"same audit")
  expect_error(generate_report(a,file=tempfile(fileext=".html")),".md")
  expect_error(generate_report(a,file=file.path(tempfile(),"report.md")),"parent directory")
  expect_error(generate_report(a,overwrite=NA),"overwrite")
})

test_that("single-class warnings appear in the report", {
  a <- suppressWarnings(audit_binary(data.frame(y=c(0,0),p=c(.1,.2)),"y","p"))
  out <- generate_report(a,file=tempfile(fileext=".md"))
  on.exit(unlink(unlist(out)))
  text <- paste(readLines(out$report),collapse="\n")
  expect_match(text,"AUROC is undefined")
  expect_match(text,"Precision is undefined")
})
